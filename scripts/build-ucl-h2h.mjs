// One-off generator for src/data/uclHeadToHead.js — every past Champions
// League (incl. European Cup and qualifying) meeting between this season's
// 36 teams, from UEFA's official match API. Re-run once a season (update
// TEAMS + LAST_SEASON) — the in-progress season comes from our own DB.
//   node scripts/build-ucl-h2h.mjs
import fs from 'fs';
import { getMatches } from 'uefa-api';

// Our team name (matches.team_a/team_b, trimmed) → UEFA team id.
const TEAMS = {
  'Club Brugge': '50043', 'Aston villa': '52683', 'AEK Athens': '50129', 'Lask': '63405', 'Real Madrid': '50051',
  'Inter': '50138', 'Dortmund': '52758', 'Villarreal': '70691', 'Porto': '50064', 'Manchaster City': '52919',
  'LOSC LIlle': '75797', 'Real Betis': '52265', 'Barcelona': '50080', 'Feyenoord': '52749', 'Stuttgart': '50107',
  'Viking': '52319', 'Paris': '52747', 'Slovan Bratislava': '52797', 'Liverpool': '7889', 'Atletico Madrid': '50124',
  'Sporting Lisbon': '50149', 'Galatasaray': '50067', 'Napoli': '50136', 'Arsenal': '52280', 'PSV': '50062',
  'Shakhtar Donetsk': '52707', 'Fenerbahce': '52692', 'AS Roma': '50137', 'Bayern Munich': '50037', 'Bodø/Glimt': '59333',
  'Manchester United': '52682', 'Sabah FC': '2609356', 'Slavia Prague': '52498', 'RC Lens': '52277', 'Como': '79946',
  'Leipzig': '2603790',
};
const FIRST_SEASON = 1956; // UEFA labels a season by the year it ends in
const LAST_SEASON = 2026;  // last completed season

const ids = new Set(Object.values(TEAMS));
const pairs = {};
let total = 0;
for (let y = FIRST_SEASON; y <= LAST_SEASON; y++) {
  let off = 0;
  for (;;) {
    const page = await getMatches({ competitionId: '1', seasonYear: String(y) }, undefined, 500, off);
    for (const m of page) {
      const h = m.homeTeam?.id, a = m.awayTeam?.id, t = m.score?.total;
      if (!ids.has(h) || !ids.has(a) || !t || t.home == null) continue;
      const key = [h, a].sort().join('-');
      const pen = m.score?.penalty;
      // [date, homeId, homeGoals, awayGoals, round, pensHome, pensAway]
      const row = [m.kickOffTime?.date, h, t.home, t.away, m.round?.metaData?.name || ''];
      if (pen && pen.home != null) row.push(pen.home, pen.away);
      (pairs[key] ||= []).push(row);
      total++;
    }
    if (page.length < 500) break;
    off += 500;
  }
  process.stdout.write(`${y} `);
}
Object.values(pairs).forEach((list) => list.sort((p, q) => q[0].localeCompare(p[0])));

const out = `// GENERATED by scripts/build-ucl-h2h.mjs — do not edit by hand.
// Every Champions League / European Cup meeting (incl. qualifying) between
// this season's 36 teams, ${FIRST_SEASON - 1}/${String(FIRST_SEASON).slice(2)}–${LAST_SEASON - 1}/${String(LAST_SEASON).slice(2)}, from UEFA's official match API.
// Row: [date, homeUefaId, homeGoals, awayGoals, round, pensHome?, pensAway?]
export const UEFA_TEAM_IDS = ${JSON.stringify(TEAMS, null, 2)};

export const UCL_H2H = ${JSON.stringify(pairs)};
`;
fs.writeFileSync('src/data/uclHeadToHead.js', out);
console.log(`\n${total} matches, ${Object.keys(pairs).length} pairs`);
